using System.Net;
using BinSight.Core.Analysis;
using BinSight.Core.Checks;

namespace BinSight.Core.Reporting;

/// <summary>
/// Self-contained HTML report with per-check security explanations.
/// Opens in modern browsers on Windows 10 and Windows 11 (no ActiveX).
/// </summary>
public sealed class HtmlReporter : IReporter
{
    public string FileExtension => "html";

    public void Write(TextWriter writer, AnalysisReport report, bool verbose)
    {
        writer.WriteLine("<!doctype html>");
        writer.WriteLine("<html lang=\"en\"><head><meta charset=\"utf-8\"/>");
        writer.Write("<title>BinSight report – ");
        writer.Write(WebUtility.HtmlEncode(Path.GetFileName(report.TargetPath)));
        writer.WriteLine("</title>");
        writer.WriteLine("<style>");
        writer.WriteLine(Css);
        writer.WriteLine("</style></head><body>");

        writer.WriteLine("<header>");
        writer.WriteLine("<h1>BinSight Analysis Report</h1>");
        writer.WriteLine($"<p class=\"meta\">Generated {DateTimeOffset.Now:yyyy-MM-dd HH:mm:ss zzz}</p>");
        writer.WriteLine("</header>");

        writer.WriteLine("<section class=\"summary\">");
        writer.WriteLine("<dl>");
        Dl(writer, "Target", report.TargetPath);
        if (report.Image is not null)
        {
            var h = report.Image.Headers;
            Dl(writer, "Machine", h.MachineName);
            Dl(writer, "Kind", h.IsPe32Plus ? "PE32+ (64-bit)" : "PE32 (32-bit)");
            Dl(writer, "Type", (h.IsDll ? "DLL" : "EXE") + (report.Image.IsManaged ? " (managed)" : " (native)"));
            Dl(writer, "DllCharacteristics", $"0x{h.DllCharacteristics:X4}");
            Dl(writer, "Linker Version", $"{h.MajorLinkerVersion}.{h.MinorLinkerVersion:D2}");
        }
        if (report.Era is not null)
            Dl(writer, "Binary era", $"{report.Era.Label} — {report.Era.Detail}");
        Dl(writer, "Symbols", report.Symbols.Summary);
        Dl(writer, "Checks run", report.Results.Count.ToString());
        Dl(writer, "Duration", $"{(report.FinishedUtc - report.StartedUtc).TotalMilliseconds:F0} ms");
        writer.WriteLine("</dl>");

        writer.WriteLine("<aside class=\"symbols-note\"><strong>Symbols note:</strong> BinSight analyzes PE security properties without private PDBs. ");
        writer.Write(WebUtility.HtmlEncode(
            report.Symbols.SymbolsAvailable
                ? "A PDB was located; enhanced CRT /GS helper confirmation ran."
                : "Providing matching symbols via /SymPath enables deeper per-function /GS and CRT helper confirmation that BinScope 2014 required private symbols for."));
        writer.WriteLine("</aside>");

        writer.WriteLine("<aside class=\"triage-note\"><strong>How to read Failures:</strong> ");
        writer.Write("A Fail is a finding to triage, not always a confirmed vulnerability. Each result includes ");
        writer.Write("<em>when the Fail may be expected</em>, <em>when to treat it as a real issue</em>, and ");
        writer.Write("<em>questions to ask the application team</em>. Correlate related checks (for example GS + default cookie, or DYNAMICBASE + relocations) before filing defects.");
        writer.WriteLine("</aside>");

        writer.WriteLine("<div class=\"totals\">");
        Pill(writer, "pass", $"{report.PassCount} pass");
        Pill(writer, "fail", $"{report.FailCount} fail");
        Pill(writer, "error", $"{report.ErrorCount} error");
        Pill(writer, "na", $"{report.NotApplicableCount} n/a");
        writer.WriteLine("</div></section>");

        // HTML is the human-readable teaching report: always include every check with
        // full Pass/Fail security explanations (verbose is reserved for console brevity).
        writer.WriteLine("<section class=\"results\">");
        foreach (var r in report.Results.OrderBy(r => StatusSortKey(r.Status)).ThenBy(r => r.CheckName, StringComparer.OrdinalIgnoreCase))
            WriteResultCard(writer, r);
        writer.WriteLine("</section>");
        _ = verbose; // retained for IReporter signature / future filtering toggles

        writer.WriteLine("<footer><p>Generated by <strong>BinSight</strong> — Copyright (C) 2026 Ray Carioto " +
                         "&lt;raymond.carioto@gmail.com&gt;. " +
                         "Licensed under the GNU General Public License v3.0 or later. " +
                         "A Windows 10 / Windows 11 replacement for Microsoft BinScope 2014.</p></footer>");
        writer.WriteLine("</body></html>");
    }

    private static void WriteResultCard(TextWriter writer, CheckResult r)
    {
        var g = SecurityExplanationFormatter.ResolveGuide(r);
        string cls = r.Status switch
        {
            CheckStatus.Pass => "pass",
            CheckStatus.Fail => "fail",
            CheckStatus.Error => "error",
            _ => "na",
        };

        writer.WriteLine($"<article class=\"finding {cls}\">");
        writer.WriteLine("<header class=\"finding-head\">");
        writer.WriteLine($"  <span class=\"pill {cls}\">{r.Status}</span>");
        writer.WriteLine($"  <h2 class=\"name\">{WebUtility.HtmlEncode(r.CheckName)}</h2>");
        writer.WriteLine("</header>");
        writer.WriteLine($"<p class=\"finding-msg\">{WebUtility.HtmlEncode(r.Message)}</p>");

        if (r.Details is { Count: > 0 })
        {
            writer.WriteLine("<ul class=\"finding-details\">");
            foreach (var d in r.Details)
                writer.WriteLine($"  <li>{WebUtility.HtmlEncode(d)}</li>");
            writer.WriteLine("</ul>");
        }

        writer.WriteLine("<div class=\"explain\">");
        writer.WriteLine("<h3>What this check covers</h3>");
        ExplainRow(writer, "Purpose", g.Purpose);
        ExplainRow(writer, "Why it matters", g.WhyItMatters);
        ExplainRow(writer, "Role in the binary", g.RoleInBinary);

        writer.WriteLine($"<h3>What <em>{WebUtility.HtmlEncode(r.Status.ToString())}</em> means here</h3>");
        writer.WriteLine($"<p class=\"meaning {cls}\">{WebUtility.HtmlEncode(g.MeaningFor(r.Status))}</p>");

        // Triage guidance is most useful on Fail/Error; still available collapsed on Pass/N/A.
        bool emphasizeTriage = r.Status is CheckStatus.Fail or CheckStatus.Error;
        if (emphasizeTriage)
        {
            writer.WriteLine("<div class=\"triage\">");
            writer.WriteLine("<h3>Triage: expected noise vs real issue</h3>");
            ExplainRow(writer, "When this Fail may be expected", g.WhenFailMayBeExpected);
            ExplainRow(writer, "Treat as a real issue when", g.RealIssueSignal);
            writer.WriteLine("<h3>Ask the application team</h3>");
            writer.WriteLine("<ol class=\"ask-team\">");
            foreach (var q in g.AskTheTeam)
                writer.WriteLine($"  <li>{WebUtility.HtmlEncode(q)}</li>");
            writer.WriteLine("</ol>");
            writer.WriteLine("</div>");
        }
        else
        {
            writer.WriteLine("<details class=\"alt triage-details\"><summary>Triage notes &amp; questions for follow-up</summary>");
            ExplainRow(writer, "When a Fail may be expected", g.WhenFailMayBeExpected);
            ExplainRow(writer, "Treat as a real issue when", g.RealIssueSignal);
            writer.WriteLine("<p><strong>Ask the application team:</strong></p>");
            writer.WriteLine("<ol class=\"ask-team\">");
            foreach (var q in g.AskTheTeam)
                writer.WriteLine($"  <li>{WebUtility.HtmlEncode(q)}</li>");
            writer.WriteLine("</ol></details>");
        }

        // Always show the counterpart wording so readers understand both outcomes.
        if (r.Status != CheckStatus.Pass)
        {
            writer.WriteLine("<details class=\"alt\"><summary>What a Pass would mean</summary>");
            writer.WriteLine($"<p>{WebUtility.HtmlEncode(g.IfPasses)}</p></details>");
        }
        if (r.Status != CheckStatus.Fail)
        {
            writer.WriteLine("<details class=\"alt\"><summary>What a Fail would mean</summary>");
            writer.WriteLine($"<p>{WebUtility.HtmlEncode(g.IfFails)}</p></details>");
        }

        writer.WriteLine("</div></article>");
    }

    private static void ExplainRow(TextWriter w, string label, string text)
    {
        w.Write("<p><strong>");
        w.Write(WebUtility.HtmlEncode(label));
        w.Write(":</strong> ");
        w.Write(WebUtility.HtmlEncode(text));
        w.WriteLine("</p>");
    }

    private static int StatusSortKey(CheckStatus s) => s switch
    {
        CheckStatus.Fail => 0,
        CheckStatus.Error => 1,
        CheckStatus.Pass => 2,
        CheckStatus.NotApplicable => 3,
        _ => 4,
    };

    private static void Dl(TextWriter w, string label, string value)
    {
        w.Write("<dt>"); w.Write(WebUtility.HtmlEncode(label)); w.Write("</dt><dd>");
        w.Write(WebUtility.HtmlEncode(value)); w.WriteLine("</dd>");
    }

    private static void Pill(TextWriter w, string cls, string text)
    {
        w.Write($"<span class=\"pill {cls}\">");
        w.Write(WebUtility.HtmlEncode(text));
        w.WriteLine("</span>");
    }

