namespace BinSight.Core.PE;

/// <summary>
/// Decoded "Rich" header (undocumented block of <c>comp.id</c> values inserted by
/// Microsoft's linker). Used for compiler/linker version and tooling detection.
/// </summary>
public sealed record RichHeader(uint XorKey, IReadOnlyList<RichEntry> Entries);

/// <summary>A single <c>comp.id</c> entry decoded from the Rich header.</summary>
/// <param name="ProductId">The <c>prodid</c> (upper 16 bits of comp.id).</param>
/// <param name="BuildNumber">The build number (lower 16 bits of comp.id).</param>
/// <param name="UseCount">Number of object files or modules that used this tool.</param>
public sealed record RichEntry(ushort ProductId, ushort BuildNumber, uint UseCount)
{
    /// <summary>Best-effort human-readable name for <see cref="ProductId"/>.</summary>
    public string ProductName => RichProductDatabase.NameFor(ProductId);
}

